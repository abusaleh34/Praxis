export function problemGuidance(lesson: string, variant: number) {
  const v = ((variant % 3) + 3) % 3;
  const meta = lessonById.get(lesson);
  if (!meta || !variants[lesson]) throw new Error('Unknown lesson');
  const [bridge, fast] = variants[lesson][v];
  const explanationLesson =
    lesson === 'triangle' ? ['triangle', 'isosceles', 'exterior'][v] : lesson;
  const explanationTarget = lesson === 'rectangle' && v === 1 ? 'perimeter' : 'area';
  return {
    bridge,
    fast,
    condition:
      lesson === 'parallel' && v === 1
        ? 'الزاويتان متجاورتان على خط مستقيم؛ لا تحتاج هذه العلاقة إلى شرط التوازي.'
        : lesson === 'triangle' && v > 0
          ? lessonById.get(explanationLesson)!.condition
          : meta.condition,
    explanationHref: `/mentor?skill=${explanationLesson}&view=learn&target=${explanationTarget}`,
  };
}
