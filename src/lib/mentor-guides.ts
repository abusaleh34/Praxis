export type GuideStep = { question: string; choices: string[]; answer: number; hint: string };
export function guideFor(lesson: string, seed: number, variant: number): GuideStep[] {
  const n = Math.abs(seed) % 7,
    v = ((variant % 3) + 3) % 3;
  const step = (question: string, right: string, wrong: string[], hint: string): GuideStep => {
    const choices = [right, ...wrong];
    const shift = (n + v) % choices.length;
    return {
      question,
      choices: [...choices.slice(shift), ...choices.slice(0, shift)],
      answer: (choices.length - shift) % choices.length,
      hint,
    };
  };
  if (lesson === 'circle')
    return [
      step(
        'أين يقع رأس الزاوية المطلوبة؟',
        v === 1 ? 'في مركز الدائرة' : 'على محيط الدائرة',
        [v === 1 ? 'على محيط الدائرة' : 'في مركز الدائرة', 'خارج الدائرة'],
        v === 1
          ? 'المطلوب زاوية مركزية؛ كلمة مركزية تحدد مكان رأسها.'
          : 'المطلوب زاوية محيطية؛ رأسها نقطة على الدائرة.',
      ),
      step(
        'للزاويتين اللتين تقابلان القوس نفسه، ماذا نفعل بقياس الزاوية المعطاة؟',
        v === 1 ? 'نضاعفه' : v === 2 ? 'نبقيه كما هو' : 'نأخذ نصفه',
        v === 1
          ? ['نأخذ نصفه', 'نبقيه كما هو']
          : v === 2
            ? ['نضاعفه', 'نأخذ نصفه']
            : ['نضاعفه', 'نبقيه كما هو'],
        'المركزية ضعف المحيطية؛ والمحيطيتان اللتان تقابلان القوس نفسه من الجهة نفسها متساويتان.',
      ),
    ];
  if (lesson === 'rectangle')
    return [
      step(
        'هل يبحث السؤال عن تغطية الداخل أم طول الحدود أم ضلع مجهول؟',
        ['تغطية الداخل', 'طول الحدود', 'ضلع مجهول'][v],
        ['تغطية الداخل', 'طول الحدود', 'ضلع مجهول'].filter((_, i) => i !== v),
        'المساحة تغطي الداخل، والمحيط يجمع الحدود، والعرض طول ضلع.',
      ),
      step(
        'أي علاقة تناسب المطلوب؟',
        ['الطول × العرض', '٢ × (الطول + العرض)', 'المساحة ÷ الطول'][v],
        ['الطول × العرض', '٢ × (الطول + العرض)', 'المساحة ÷ الطول'].filter((_, i) => i !== v),
        'اربط الوحدة بالمعنى: المساحة مربعة، والمحيط والعرض وحدتهما طول.',
      ),
    ];
  if (lesson === 'triangle' && v === 0)
    return [
      step(
        'ما مجموع زوايا المثلث؟',
        '١٨٠°',
        ['٩٠°', '٣٦٠°'],
        'قارنها بزاوية مستقيمة؛ الزوايا الثلاث تجتمع عليها.',
      ),
      step(
        'قبل إيجاد الزاوية الثالثة، ما العملية التي تجمع الزاويتين المعروفتين؟',
        `${30 + n * 5} + ${40 + n * 3}`,
        [`${30 + n * 5} × ${40 + n * 3}`, `${30 + n * 5} − ${40 + n * 3}`],
        'نحتاج مجموع الجزأين المعلومين ثم نطرحه من مجموع المثلث.',
      ),
    ];
  if (lesson === 'isosceles' || (lesson === 'triangle' && v === 1))
    return [
      step(
        'ما العلاقة بين زاويتي قاعدة المثلث متساوي الساقين؟',
        'متساويتان',
        ['مجموعهما دائمًا ٩٠°', 'إحداهما ضعف الأخرى'],
        'الضلعان المتساويان تقابلهما زاويتان متساويتان.',
      ),
      step(
        'بعد طرح زاوية الرأس من ١٨٠°، ماذا تمثل النتيجة؟',
        'مجموع زاويتي القاعدة',
        ['زاوية قاعدة واحدة', 'طول القاعدة'],
        'المتبقي يشمل زاويتين. نقسمه بالتساوي فقط إذا أردنا زاوية واحدة.',
      ),
    ];
  if (lesson === 'exterior' || lesson === 'triangle')
    return [
      step(
        'الخارجية تساوي أي مجموع؟',
        'الداخليتين البعيدتين',
        ['الداخلية المجاورة وحدها', 'جميع زوايا المثلث'],
        'الخارجية والداخلية المجاورة تكملان زاوية مستقيمة؛ البعيدتان تكملان المجاورة داخل المثلث.',
      ),
    ];
  if (lesson === 'parallel')
    return [
      step(
        'أي علاقة تستخدم لهذا السؤال؟',
        v === 1 ? 'زاويتان مجموعهما ١٨٠°' : 'زاويتان متساويتان',
        [v === 1 ? 'زاويتان متساويتان' : 'زاويتان مجموعهما ١٨٠°', 'زاويتان مجموعهما ٣٦٠°'],
        'المتجاورتان على مستقيم متكاملتان؛ والمتناظرتان والمتبادلتان عند التوازي متساويتان.',
      ),
    ];
  if (lesson === 'right')
    return [
      step(
        'أين يوجد الوتر؟',
        'مقابل الزاوية القائمة',
        ['أي ضلع بجوار القائمة', 'الضلع الأقصر'],
        'الوتر هو الأطول ويقابل ٩٠°.',
      ),
      step(
        'مجموع مربعي الضلعين القائمين يساوي ماذا؟',
        'مربع الوتر',
        ['الوتر مباشرة', 'محيط المثلث'],
        'أخذ الجذر خطوة إضافية نحتاجها فقط عند طلب الطول.',
      ),
    ];
  if (lesson === 'polygon')
    return [
      step(
        'ما مجموع الزوايا الخارجية لدورة حول المضلع؟',
        '٣٦٠°',
        ['١٨٠°', '٩٠°'],
        'أكمل دورة واحدة حتى تعود للاتجاه نفسه.',
      ),
      step(
        'لماذا يجوز تقسيم الدورة على عدد الأضلاع هنا؟',
        'لأن المضلع منتظم',
        ['لأن أي مضلع زواياه متساوية', 'لأن له أكثر من ضلعين'],
        'الانتظام يضمن تساوي الزوايا الخارجية.',
      ),
    ];
  if (lesson === 'ratio')
    return [
      step(
        'كيف نجد سعر دفتر واحد؟',
        'نقسم الثمن على عدد الدفاتر',
        ['نضرب الثمن في عدد الدفاتر', 'نطرح العدد من الثمن'],
        'قسّم تكلفة المجموعة بالتساوي على وحداتها.',
      ),
    ];
  if (lesson === 'fractions')
    return [
      step(
        'على أي قيمة نحسب النسبة؟',
        'القيمة الأصلية',
        ['القيمة بعد التغيير', 'عدد النسبة وحده'],
        'النسبة جزء من أصل محدد في السؤال.',
      ),
      step(
        'بعد حساب الجزء، كيف نصل للمطلوب؟',
        ['نكتفي بالجزء', 'نطرح الجزء من الأصل', 'نضيف الجزء إلى الأصل'][v],
        ['نكتفي بالجزء', 'نطرح الجزء من الأصل', 'نضيف الجزء إلى الأصل'].filter((_, i) => i !== v),
        'طلب نسبة من كمية يختلف عن السعر بعد الخصم أو الزيادة.',
      ),
    ];
  if (lesson === 'speed' || lesson === 'physics')
    return [
      step(
        'أي كمية يطلبها السؤال؟',
        ['المسافة', 'الزمن', 'السرعة'][v],
        ['المسافة', 'الزمن', 'السرعة'].filter((_, i) => i !== v),
        'اقرأ آخر جملة وحدد وحدة الجواب.',
      ),
      step(
        'أي علاقة تناسب هذه الكمية؟',
        ['السرعة × الزمن', 'المسافة ÷ السرعة', 'المسافة ÷ الزمن'][v],
        ['السرعة × الزمن', 'المسافة ÷ السرعة', 'المسافة ÷ الزمن'].filter((_, i) => i !== v),
        'المسافة = السرعة × الزمن؛ أعد ترتيب العلاقة لعزل المطلوب.',
      ),
    ];
  if (lesson === 'chemistry')
    return [
      step(
        'ماذا تعني الكتلة المولية؟',
        'كتلة مول واحد',
        ['عدد المولات في كل عينة', 'حجم العينة'],
        'وحدتها غرام لكل مول.',
      ),
      step(
        'الكتلة الكلية تساوي ماذا؟',
        'عدد المولات × الكتلة المولية',
        ['عدد المولات + الكتلة المولية', 'الكتلة المولية ÷ عدد المولات'],
        'تصور وحدات متساوية، كتلة كل وحدة هي الكتلة المولية.',
      ),
    ];
  if (lesson === 'analogy')
    return [
      step(
        'ما نوع العلاقة في الزوج الأول؟',
        ['أداة ووظيفتها', 'جزء وكل', 'حاجة وما يسدها'][v],
        ['أداة ووظيفتها', 'جزء وكل', 'حاجة وما يسدها'].filter((_, i) => i !== v),
        [
          'نسأل: ما الذي نفعله بالقلم؟',
          'نسأل: هل الصفحة تضم الكتاب أم الكتاب يضم الصفحة؟',
          'نسأل: ما الذي يزيل العطش؟',
        ][v],
      ),
      step(
        'كيف نختبر العلاقة في الخيارات؟',
        'بنفس الجملة وبنفس ترتيب الكلمتين',
        ['بتشابه الموضوع فقط', 'بقلب ترتيب الكلمات دائمًا'],
        'حافظ على اتجاه العلاقة عند تطبيقها على الزوج الثاني.',
      ),
    ];
  return [
    step(
      'ما مصدر الدليل الذي نحتاجه للإجابة؟',
      'الجملة المرتبطة بالمطلوب في النص',
      ['معلومة من خارج النص', 'أي تعميم يبدو معقولًا'],
      'حدّد هل المطلوب عامل تغيّر أم سبب التكرار أم استنتاج.',
    ),
    step(
      'هل تكفي تجربة واحدة للحكم على كل النباتات دائمًا؟',
      'لا، نلتزم بما لوحظ في التجربة',
      ['نعم، دون تكرار', 'نعم، مهما اختلفت الظروف'],
      'انتبه لكلمات التعميم؛ النص يطلب التحقق قبل التعميم.',
    ),
  ];
}

export function publicGuide(steps: GuideStep[], index: number) {
  const s = steps[index];
  return s ? { question: s.question, choices: s.choices, index, total: steps.length } : null;
}
